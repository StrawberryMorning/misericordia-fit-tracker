export function buildRoutinesFromSplit(
  split: SplitGuideItem,
  includeSuggestedExercises: boolean
): WorkoutRoutine[] {
  return split.days.map((day, dIdx) => ({
    id: `routine-${split.id}-${dIdx}-${Date.now()}`,
    name: day.title,
    description: `${split.name} • Foco: ${day.focus}`,
    exercises: includeSuggestedExercises
      ? day.suggestedExercises.map((ex, eIdx) => ({
          id: `ex-${split.id}-${dIdx}-${eIdx}-${Date.now()}`,
          name: ex.name,
          muscleGroup: ex.muscleGroup,
          targetSets: ex.targetSets,
          targetReps: ex.targetReps,
          restSeconds: ex.restSeconds,
        }))
      : [],
  }));
}
